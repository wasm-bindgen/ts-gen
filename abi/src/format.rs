//! The annotated WAT template: an [`Abi`] as a module whose imports are
//! its functions, with `@abi.*` annotations carrying the rest. `ABI.md`
//! is the specification; [`emit`] and [`parse`] are its reference
//! writer and reader, and `parse(&emit(abi)) == abi`.

use std::fmt::Write;

use crate::sexpr::{self, Node};
use crate::wat::{ident, string, ANYREFS};
use crate::{
    Abi, AbiFunction, AbiHandler, AbiOp, AbiOwner, AbiParam, Head, OwnerKind, WasmType,
    BINDINGS_SPECIFIER, BUILTINS_SPECIFIER, UNDEFINED_GLOBAL,
};

/// The format version `emit` writes and `parse` reads.
pub const VERSION: u32 = 1;

/// Write `abi` as a template. The owners must be in [`Abi::canonicalize`]
/// order for the file to read back as `abi`.
pub fn emit(abi: &Abi) -> String {
    let mut out = String::new();
    out.push_str(";; Generated by ts-gen: the Wasm ABI as an import template. See ABI.md\n");
    out.push_str(";; for the format; the @abi annotations are ignored by WAT tools.\n;;\n");
    out.push_str(";; Scalars: number -> f64, boolean -> i32, bigint -> i64.\n");
    out.push_str(";; All other values (strings, objects, null/undefined) are externref,\n");
    out.push_str(";; as JS produced them. Per position, embed also accepts anyref, and\n");
    out.push_str(";; (ref extern) / (ref any) where the TS type never admits null.\n;;\n");
    out.push_str(";; Unused imports need not be deleted; embed prunes to what you use.\n");
    out.push_str("(module\n");
    let _ = writeln!(out, "  (@abi.version {VERSION})");
    if abi.functions.iter().any(|f| f.variadic) {
        out.push_str("  (type $anyrefs (array (mut anyref)))\n");
    }

    let mut written = vec![false; abi.owners.len()];
    let mut group: Option<(Option<&str>, Option<&str>)> = None;
    for f in &abi.functions {
        let this_group = (f.module.as_deref(), f.owner.as_deref());
        if group != Some(this_group) {
            group = Some(this_group);
            out.push('\n');
            if let Some(path) = &f.owner {
                if let Some(i) = abi
                    .owners
                    .iter()
                    .position(|o| &o.path == path && o.module == f.module)
                {
                    if !std::mem::replace(&mut written[i], true) {
                        owner(&mut out, &abi.owners[i]);
                    }
                }
            }
        }
        function(&mut out, f);
    }
    let rest: Vec<&AbiOwner> = abi
        .owners
        .iter()
        .zip(&written)
        .filter(|(_, w)| !**w)
        .map(|(o, _)| o)
        .collect();
    if !rest.is_empty() {
        out.push_str("\n  ;; Owners with no functions of their own.\n");
        for o in rest {
            owner(&mut out, o);
        }
    }

    out.push_str("\n  ;; `undefined`, for passing where TS says `T | undefined`.\n");
    let _ = writeln!(
        out,
        "  (import {} {} (global $undefined externref))",
        string(BUILTINS_SPECIFIER),
        string(UNDEFINED_GLOBAL)
    );
    out.push_str("  ;; JSPI: suspends on a Promise and returns its value. Importing this\n");
    out.push_str("  ;; selects JSPI mode in `embed`, which wraps the handlers with promising.\n");
    let _ = writeln!(
        out,
        "  (import {} \"await\" (func $await (param externref) (result externref)))",
        string(BUILTINS_SPECIFIER)
    );

    if !abi.handlers.is_empty() {
        out.push_str("\n  ;; --provides: fill these in; embed publishes them at their JS paths.\n");
    }
    for h in &abi.handlers {
        handler(&mut out, h);
    }
    out.push_str(")\n");
    out
}

fn owner(out: &mut String, o: &AbiOwner) {
    let _ = write!(out, "  (@abi.{} {}", o.kind.keyword(), string(&o.path));
    if let Some(m) = &o.module {
        let _ = write!(out, " (module {})", string(m));
    }
    for a in &o.aliases {
        let _ = write!(out, " (alias {})", string(a));
    }
    for e in &o.extends {
        let _ = write!(out, " (extends {})", string(e));
    }
    if let Some(d) = &o.doc {
        let _ = write!(out, " (doc {})", string(d));
    }
    out.push_str(")\n");
}

fn op(op: &AbiOp) -> String {
    let path = |p: &[String]| {
        p.iter()
            .map(|s| format!(" {}", string(s)))
            .collect::<String>()
    };
    match op {
        AbiOp::Get { name } => format!("(@abi.get {})", string(name)),
        AbiOp::Set { name } => format!("(@abi.set {})", string(name)),
        AbiOp::Call { name } => format!("(@abi.call {})", string(name)),
        AbiOp::StaticGet { path: p, name } => {
            format!("(@abi.get {} (on{}))", string(name), path(p))
        }
        AbiOp::StaticSet { path: p, name } => {
            format!("(@abi.set {} (on{}))", string(name), path(p))
        }
        AbiOp::StaticCall { path: p, name } => {
            format!("(@abi.call {} (on{}))", string(name), path(p))
        }
        AbiOp::Construct { path: p } => format!("(@abi.new{})", path(p)),
        AbiOp::NewObject => "(@abi.object)".into(),
        AbiOp::IsUndefined => "(@abi.is-undefined)".into(),
        AbiOp::NumberValue => "(@abi.number)".into(),
        AbiOp::Undefined => "(@abi.undefined)".into(),
    }
}

/// `(@abi.ref ...)` for a reference position, or nothing.
fn reference(ty: WasmType, head: Option<&Head>) -> String {
    let WasmType::ExternRef { null, undefined } = ty else {
        return String::new();
    };
    let mut parts: Vec<String> = Vec::new();
    match head {
        Some(Head::Declared(p)) => parts.push(string(p)),
        Some(Head::String) => parts.push("string".into()),
        Some(Head::Number) => parts.push("number".into()),
        Some(Head::Boolean) => parts.push("boolean".into()),
        Some(Head::BigInt) => parts.push("bigint".into()),
        None => {}
    }
    if null {
        parts.push("null".into());
    }
    if undefined {
        parts.push("undefined".into());
    }
    if parts.is_empty() {
        String::new()
    } else {
        format!(" (@abi.ref {})", parts.join(" "))
    }
}

fn positions(
    out: &mut String,
    params: &[AbiParam],
    variadic: bool,
    result: Option<WasmType>,
    result_head: Option<&Head>,
    annotate: bool,
) {
    for (i, p) in params.iter().enumerate() {
        let rest = variadic && i == params.len() - 1;
        let ty = if rest { ANYREFS } else { p.ty.wat() };
        let r = if annotate && !rest {
            reference(p.ty, p.head.as_ref())
        } else {
            String::new()
        };
        let _ = write!(out, "\n      (param ${} {ty}{r})", p.name);
    }
    if let Some(t) = result {
        let r = if annotate {
            reference(t, result_head)
        } else {
            String::new()
        };
        let _ = write!(out, "\n      (result {}{r})", t.wat());
    }
}

fn function(out: &mut String, f: &AbiFunction) {
    let module = f.import_module();
    let id = |name: &str| match &f.module {
        Some(spec) => ident(&format!("{spec}:{name}")),
        None => ident(name),
    };
    let _ = write!(
        out,
        "  (import {} {}\n    (func ${} {}",
        string(module),
        string(&f.name),
        id(&f.name),
        op(&f.op)
    );
    if let Some(o) = &f.owner {
        let _ = write!(out, " (@abi.owner {})", string(o));
    }
    let _ = write!(out, "\n      (@abi.ts {})", string(&f.ts));
    if let Some(d) = &f.doc {
        let _ = write!(out, "\n      (@abi.doc {})", string(d));
    }
    positions(
        out,
        &f.params,
        f.variadic,
        f.result,
        f.result_head.as_ref(),
        true,
    );
    out.push_str("))\n");
    for alias in &f.aliases {
        let _ = write!(
            out,
            "  (import {} {}\n    (func ${} (@abi.alias {})",
            string(module),
            string(alias),
            id(alias),
            string(&f.name)
        );
        positions(out, &f.params, f.variadic, f.result, None, false);
        out.push_str("))\n");
    }
}

fn handler(out: &mut String, h: &AbiHandler) {
    let _ = write!(out, "\n  (func (export {}) (@abi.provide", string(&h.name));
    for s in &h.path {
        let _ = write!(out, " {}", string(s));
    }
    out.push(')');
    if h.promise {
        out.push_str(" (@abi.promise)");
    }
    let _ = write!(out, "\n      (@abi.ts {})", string(&h.ts));
    if let Some(d) = &h.doc {
        let _ = write!(out, "\n      (@abi.doc {})", string(d));
    }
    positions(
        out,
        &h.params,
        false,
        h.result,
        h.result_head.as_ref(),
        true,
    );
    out.push_str("\n    unreachable)\n");
}

/// Read a template written by [`emit`], or any file following `ABI.md`.
pub fn parse(src: &str) -> Result<Abi, String> {
    let root = sexpr::read(src)?;
    let items = match root.list() {
        Some([Node::Atom(m), items @ ..]) if m == "module" => items,
        _ => return Err("expected `(module ...)`".into()),
    };
    let mut abi = Abi::default();
    let mut version = None;
    let mut aliases: Vec<(String, String, String)> = Vec::new();
    for item in items {
        let Some(head) = item.head() else {
            continue;
        };
        let args = &item.list().unwrap_or_default()[1..];
        match head {
            "@abi.version" => {
                let v = args
                    .first()
                    .and_then(Node::atom)
                    .and_then(|a| a.parse::<u32>().ok())
                    .ok_or("`@abi.version` takes a number")?;
                if v != VERSION {
                    return Err(format!("format version {v}, this reader reads {VERSION}"));
                }
                version = Some(v);
            }
            "import" => {
                let module = str_at(args, 0, "import module")?;
                let name = str_at(args, 1, "import name")?;
                if module == BUILTINS_SPECIFIER {
                    continue;
                }
                let func = args
                    .get(2)
                    .filter(|n| n.head() == Some("func"))
                    .and_then(Node::list)
                    .ok_or_else(|| format!("import {name:?} is not a function"))?;
                if let Some(primary) = annotation(func, "@abi.alias") {
                    aliases.push((
                        module.into(),
                        name.into(),
                        str_at(primary, 0, "alias")?.into(),
                    ));
                    continue;
                }
                abi.functions.push(read_function(module, name, func)?);
            }
            "func" => abi
                .handlers
                .push(read_handler(item.list().unwrap_or_default())?),
            h if h.starts_with("@abi.") => {
                if let Some(kind) = OwnerKind::from_keyword(&h["@abi.".len()..]) {
                    abi.owners.push(read_owner(kind, args)?);
                }
            }
            _ => {}
        }
    }
    if version.is_none() {
        return Err("no `(@abi.version ...)`: not an ABI template".into());
    }
    for (module, name, primary) in aliases {
        let module = (module != BINDINGS_SPECIFIER).then_some(module);
        let f = abi
            .functions
            .iter_mut()
            .find(|f| f.module == module && f.name == primary)
            .ok_or_else(|| format!("alias {name:?} names {primary:?}, which is not imported"))?;
        f.aliases.push(name);
    }
    Ok(abi)
}

fn str_at<'a>(args: &'a [Node], i: usize, what: &str) -> Result<&'a str, String> {
    args.get(i)
        .and_then(Node::str)
        .ok_or_else(|| format!("expected a string for the {what}"))
}

/// The arguments of the first `(<name> ...)` among `items`.
fn annotation<'a>(items: &'a [Node], name: &str) -> Option<&'a [Node]> {
    items
        .iter()
        .find(|n| n.head() == Some(name))
        .and_then(Node::list)
        .map(|l| &l[1..])
}

fn strings(args: &[Node]) -> Result<Vec<String>, String> {
    args.iter()
        .map(|n| {
            n.str()
                .map(String::from)
                .ok_or_else(|| "expected a string".into())
        })
        .collect()
}

fn read_owner(kind: OwnerKind, args: &[Node]) -> Result<AbiOwner, String> {
    let mut o = AbiOwner {
        path: str_at(args, 0, "owner path")?.into(),
        kind,
        module: None,
        aliases: Vec::new(),
        extends: Vec::new(),
        doc: None,
    };
    for field in &args[1..] {
        let Some(l) = field.list() else { continue };
        let value = || str_at(&l[1..], 0, "owner field").map(String::from);
        match field.head() {
            Some("module") => o.module = Some(value()?),
            Some("alias") => o.aliases.push(value()?),
            Some("extends") => o.extends.push(value()?),
            Some("doc") => o.doc = Some(value()?),
            _ => {}
        }
    }
    Ok(o)
}

fn read_op(items: &[Node]) -> Result<AbiOp, String> {
    for item in items {
        let Some(head) = item.head() else { continue };
        let args = &item.list().unwrap_or_default()[1..];
        let on = || -> Result<Option<Vec<String>>, String> {
            match annotation(args, "on") {
                Some(path) => strings(path).map(Some),
                None => Ok(None),
            }
        };
        let name = || str_at(args, 0, "operation's name").map(String::from);
        return Ok(match head {
            "@abi.get" => match on()? {
                Some(path) => AbiOp::StaticGet {
                    path,
                    name: name()?,
                },
                None => AbiOp::Get { name: name()? },
            },
            "@abi.set" => match on()? {
                Some(path) => AbiOp::StaticSet {
                    path,
                    name: name()?,
                },
                None => AbiOp::Set { name: name()? },
            },
            "@abi.call" => match on()? {
                Some(path) => AbiOp::StaticCall {
                    path,
                    name: name()?,
                },
                None => AbiOp::Call { name: name()? },
            },
            "@abi.new" => AbiOp::Construct {
                path: strings(args)?,
            },
            "@abi.object" => AbiOp::NewObject,
            "@abi.is-undefined" => AbiOp::IsUndefined,
            "@abi.number" => AbiOp::NumberValue,
            "@abi.undefined" => AbiOp::Undefined,
            _ => continue,
        });
    }
    Err("no operation".into())
}

/// The parameters and result of a `func`, and whether the last parameter
/// is a variadic rest.
#[allow(clippy::type_complexity)]
fn read_positions(
    items: &[Node],
) -> Result<(Vec<AbiParam>, bool, Option<WasmType>, Option<Head>), String> {
    let mut params = Vec::new();
    let mut variadic = false;
    let mut result = None;
    let mut result_head = None;
    for item in items {
        match item.head() {
            Some("param") => {
                let l = item.list().unwrap_or_default();
                let name = l
                    .get(1)
                    .and_then(Node::atom)
                    .and_then(|a| a.strip_prefix('$'))
                    .ok_or("a parameter needs a `$name`")?;
                let rest = l.get(2).and_then(Node::list).is_some();
                variadic = rest;
                let (ty, head) = if rest {
                    (WasmType::JS, None)
                } else {
                    position(&l[2..])?
                };
                params.push(AbiParam {
                    name: name.into(),
                    ty,
                    head,
                });
            }
            Some("result") => {
                let (ty, head) = position(&item.list().unwrap_or_default()[1..])?;
                result = Some(ty);
                result_head = head;
            }
            _ => {}
        }
    }
    Ok((params, variadic, result, result_head))
}

/// A value type and its optional `(@abi.ref ...)`.
fn position(items: &[Node]) -> Result<(WasmType, Option<Head>), String> {
    let ty = items
        .first()
        .and_then(Node::atom)
        .ok_or("expected a type")?;
    let (null, undefined, head) = match annotation(items, "@abi.ref") {
        Some(args) => {
            let mut head = None;
            let (mut null, mut undefined) = (false, false);
            for a in args {
                match a {
                    Node::Str(p) => head = Some(Head::Declared(p.clone())),
                    Node::Atom(a) => match a.as_str() {
                        "null" => null = true,
                        "undefined" => undefined = true,
                        "string" => head = Some(Head::String),
                        "number" => head = Some(Head::Number),
                        "boolean" => head = Some(Head::Boolean),
                        "bigint" => head = Some(Head::BigInt),
                        _ => {}
                    },
                    Node::List(_) => {}
                }
            }
            (null, undefined, head)
        }
        None => (false, false, None),
    };
    let ty = match ty {
        "i32" => WasmType::I32,
        "i64" => WasmType::I64,
        "f64" => WasmType::F64,
        "externref" => WasmType::ExternRef { null, undefined },
        other => return Err(format!("unexpected type `{other}`")),
    };
    Ok((ty, head.filter(|_| ty.is_ref())))
}

fn optional_str(items: &[Node], name: &str) -> Result<Option<String>, String> {
    annotation(items, name)
        .map(|a| str_at(a, 0, name).map(String::from))
        .transpose()
}

fn read_function(module: &str, name: &str, func: &[Node]) -> Result<AbiFunction, String> {
    let err = |e: String| format!("import {name:?}: {e}");
    let (params, variadic, result, result_head) = read_positions(func).map_err(err)?;
    Ok(AbiFunction {
        name: name.into(),
        aliases: Vec::new(),
        owner: optional_str(func, "@abi.owner").map_err(err)?,
        op: read_op(func).map_err(err)?,
        params,
        result,
        result_head,
        ts: optional_str(func, "@abi.ts")
            .map_err(err)?
            .unwrap_or_default(),
        doc: optional_str(func, "@abi.doc").map_err(err)?,
        variadic,
        module: (module != BINDINGS_SPECIFIER).then(|| module.into()),
    })
}

fn read_handler(func: &[Node]) -> Result<AbiHandler, String> {
    let name = annotation(func, "export")
        .and_then(|a| a.first())
        .and_then(Node::str)
        .ok_or("a handler needs an `(export ...)`")?;
    let err = |e: String| format!("handler {name:?}: {e}");
    let (params, _, result, result_head) = read_positions(func).map_err(err)?;
    Ok(AbiHandler {
        name: name.into(),
        path: strings(
            annotation(func, "@abi.provide").ok_or_else(|| err("no `@abi.provide`".into()))?,
        )
        .map_err(err)?,
        params,
        result,
        result_head,
        promise: annotation(func, "@abi.promise").is_some(),
        ts: optional_str(func, "@abi.ts")
            .map_err(err)?
            .unwrap_or_default(),
        doc: optional_str(func, "@abi.doc").map_err(err)?,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn param(name: &str, ty: WasmType, head: Option<Head>) -> AbiParam {
        AbiParam {
            name: name.into(),
            ty,
            head,
        }
    }

    #[test]
    fn round_trips() {
        let headers = || Some(Head::Declared("Headers".into()));
        let mut abi = Abi {
            owners: vec![
                AbiOwner {
                    path: "Headers".into(),
                    kind: OwnerKind::Class,
                    module: None,
                    aliases: vec![],
                    extends: vec!["Base".into()],
                    doc: Some("Line one.\nSays \"hi\" \\ é".into()),
                },
                AbiOwner {
                    path: "Conn".into(),
                    kind: OwnerKind::Interface,
                    module: Some("db".into()),
                    aliases: vec!["Connection".into()],
                    extends: vec![],
                    doc: None,
                },
                AbiOwner {
                    path: "Unused".into(),
                    kind: OwnerKind::Dictionary,
                    module: None,
                    aliases: vec![],
                    extends: vec![],
                    doc: None,
                },
            ],
            functions: vec![
                AbiFunction {
                    name: "Headers.get".into(),
                    aliases: vec![],
                    owner: Some("Headers".into()),
                    op: AbiOp::Call { name: "get".into() },
                    params: vec![
                        param("this", WasmType::JS_NON_NULL, headers()),
                        param("name", WasmType::JS_NON_NULL, Some(Head::String)),
                    ],
                    result: Some(WasmType::ExternRef {
                        null: true,
                        undefined: false,
                    }),
                    result_head: Some(Head::String),
                    ts: "get(name: string): string | null".into(),
                    doc: Some("Gets.".into()),
                    variadic: false,
                    module: None,
                },
                AbiFunction {
                    name: "Conn.get".into(),
                    aliases: vec!["Connection.get".into()],
                    owner: Some("Conn".into()),
                    op: AbiOp::Call { name: "get".into() },
                    params: vec![param("this", WasmType::JS_NON_NULL, None)],
                    result: Some(WasmType::F64),
                    result_head: None,
                    ts: "get(): number".into(),
                    doc: None,
                    variadic: false,
                    module: Some("db".into()),
                },
                AbiFunction {
                    name: "log".into(),
                    aliases: vec![],
                    owner: None,
                    op: AbiOp::StaticCall {
                        path: vec![],
                        name: "log".into(),
                    },
                    params: vec![
                        param("first", WasmType::F64, None),
                        param("rest", WasmType::JS, None),
                    ],
                    result: None,
                    result_head: None,
                    ts: "log(first: number, ...rest: any[]): void".into(),
                    doc: None,
                    variadic: true,
                    module: None,
                },
                AbiFunction {
                    name: "WebAssembly.Module.new".into(),
                    aliases: vec![],
                    owner: Some("WebAssembly.Module".into()),
                    op: AbiOp::Construct {
                        path: vec!["WebAssembly".into(), "Module".into()],
                    },
                    params: vec![param("bytes", WasmType::JS, Some(Head::Number))],
                    result: Some(WasmType::JS_NON_NULL),
                    result_head: Some(Head::Declared("WebAssembly.Module".into())),
                    ts: "constructor(bytes)".into(),
                    doc: None,
                    variadic: false,
                    module: None,
                },
            ],
            handlers: vec![AbiHandler {
                name: "fetch".into(),
                path: vec!["default".into(), "fetch".into()],
                params: vec![param("request", WasmType::JS_NON_NULL, None)],
                result: Some(WasmType::JS),
                result_head: None,
                promise: true,
                ts: "fetch(request): Promise<Response>".into(),
                doc: Some("Handles.".into()),
            }],
        };
        abi.canonicalize();
        let text = emit(&abi);
        assert_eq!(parse(&text).unwrap(), abi, "{text}");
        // The template stays a module any WAT parser assembles.
        wat::parse_str(&text).unwrap();
    }

    #[test]
    fn rejects_other_versions_and_unknown_operations() {
        assert!(parse("(module (@abi.version 2))")
            .unwrap_err()
            .contains("version 2"));
        assert!(parse("(module)")
            .unwrap_err()
            .contains("not an ABI template"));
        let unknown = r#"(module (@abi.version 1)
            (import "./bindings.wasm" "x" (func $x (@abi.teleport "x"))))"#;
        assert!(parse(unknown).unwrap_err().contains("no operation"));
    }
}
