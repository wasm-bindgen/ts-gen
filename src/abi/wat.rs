//! `--target wat`: the ABI as a module template. Every function is an
//! import a language module may use, with its TS declaration alongside,
//! and every provided function is a stub export to fill in. `embed` prunes
//! the bindings to what a module actually imports.

use std::fmt::Write;

use super::{Abi, AbiFunction, AbiParam, WasmType, BUILTINS_SPECIFIER, UNDEFINED_GLOBAL};

fn has_variadic(abi: &Abi) -> bool {
    abi.functions.iter().any(|f| f.variadic)
}

pub fn generate(abi: &Abi) -> String {
    let mut out = String::new();
    out.push_str(";; Generated by ts-gen. Import template for the Wasm ABI.\n;;\n");
    out.push_str(";; Scalars: number -> f64, boolean -> i32, bigint -> i64.\n");
    out.push_str(";; All other values (strings, objects, null/undefined) are externref,\n");
    out.push_str(";; as JS produced them. Per position, embed also accepts anyref, and\n");
    out.push_str(";; (ref extern) / (ref any) where the TS type never admits null.\n;;\n");
    out.push_str(";; Import names: Type.member with _with_x suffixes for overloads.\n");
    out.push_str(";; Dictionary constructors: Type.new creates {} (empty object).\n");
    out.push_str(";; Variables: declare var x -> x getter reading it from its scope.\n;;\n");
    if !abi.modules().is_empty() {
        out.push_str(
            ";; Declarations from `declare module \"spec\"` are imported from \"spec\".\n",
        );
        out.push_str(";;\n");
    }
    out.push_str(";; Unused imports need not be deleted; embed prunes to what you use.\n");
    out.push_str("(module\n");
    if has_variadic(abi) {
        out.push_str(
            "  ;; GC array type for variadic parameters (anyref for GC language compat).\n",
        );
        out.push_str("  (type $anyrefs (array (mut anyref)))\n");
    }

    let mut owner: Option<&str> = None;
    for f in &abi.functions {
        let this_owner = f.name.rsplit_once('.').map(|(o, _)| o);
        if this_owner != owner {
            owner = this_owner;
            out.push('\n');
            if let Some(o) = owner {
                let _ = writeln!(out, "  ;; {o}");
            }
        }
        let _ = writeln!(out, "  ;; {}", f.ts);
        let module = f.import_module();
        for name in std::iter::once(&f.name).chain(&f.aliases) {
            let id = match &f.module {
                Some(spec) => ident(&format!("{spec}:{name}")),
                None => ident(name),
            };
            let _ = writeln!(
                out,
                "  (import {module:?} {name:?} (func ${id}{}{}))",
                params_variadic(&f.params, f.variadic),
                result(f.result)
            );
        }
    }

    out.push_str("\n  ;; `undefined`, for passing where TS says `T | undefined`.\n");
    let _ = writeln!(
        out,
        "  (import {BUILTINS_SPECIFIER:?} {UNDEFINED_GLOBAL:?} (global $undefined externref))"
    );
    out.push_str("\n  ;; JSPI: suspends on a Promise and returns its value. Importing this\n");
    out.push_str("  ;; selects JSPI mode in `embed`, which wraps the handlers with promising.\n");
    let _ = writeln!(
        out,
        "  (import {BUILTINS_SPECIFIER:?} \"await\" (func $await (param externref) (result externref)))"
    );

    if !abi.handlers.is_empty() {
        out.push_str("\n  ;; --provides: fill these in; embed publishes them at their JS paths.\n");
    }
    for h in &abi.handlers {
        out.push('\n');
        let _ = writeln!(out, "  ;; {}: {}", h.path.join("."), h.ts);
        let _ = writeln!(
            out,
            "  (func (export {:?}){}{}\n    unreachable)",
            h.name,
            params(&h.params),
            result(h.result)
        );
    }

    out.push_str(")\n");
    out
}

/// `Type.member` as a WAT identifier: `$Type.member` and
/// `$node:fs:readFileSync` are legal since `.`, `:` and `/` are id
/// characters; anything else becomes `_`.
pub fn ident(name: &str) -> String {
    name.chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || "!#$%&'*+-./:<=>?@\\^_`|~".contains(c) {
                c
            } else {
                '_'
            }
        })
        .collect()
}

pub fn params(params: &[AbiParam]) -> String {
    params_variadic(params, false)
}

pub fn params_variadic(params: &[AbiParam], variadic: bool) -> String {
    let mut s = String::new();
    for (i, p) in params.iter().enumerate() {
        let is_rest = variadic && i == params.len() - 1;
        let ty = if is_rest {
            "(ref null $anyrefs)"
        } else {
            p.ty.wat()
        };
        let _ = write!(s, " (param ${} {})", p.name, ty);
    }
    s
}

pub fn result(result: Option<WasmType>) -> String {
    match result {
        Some(t) => format!(" (result {})", t.wat()),
        None => String::new(),
    }
}

/// Signature text of a function, for matching a module's import types.
pub fn signature(f: &AbiFunction) -> String {
    let params_str: String = f
        .params
        .iter()
        .enumerate()
        .map(|(i, p)| {
            let is_rest = f.variadic && i == f.params.len() - 1;
            let ty = if is_rest {
                "(ref null $anyrefs)"
            } else {
                p.ty.wat()
            };
            format!(" (param {})", ty)
        })
        .collect();
    format!("(func{}{})", params_str, result(f.result))
}
