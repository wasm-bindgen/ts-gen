//! `--target wat`: the IR as a plain WAT import template, for a language
//! written in WAT by hand. One import per member with its wire signature,
//! after a comment with its IR declaration, and a stub export per provide;
//! `embed` prunes the bindings to what a module actually imports.

use std::fmt::Write;

pub use ts_gen_abi::wat::*;

use ts_gen_abi::ir::{Import, Ir, Param, Sys};
use ts_gen_abi::text::Printer;

use super::{WasmType, BINDINGS_SPECIFIER, BUILTINS_SPECIFIER, UNDEFINED_GLOBAL};

pub fn generate(ir: &Ir) -> String {
    let printer = Printer::new(ir);
    let mut out = String::new();
    out.push_str(";; Generated by ts-gen: the IR's bindings as a WAT import template. See\n");
    out.push_str(";; IR.md for the IR each comment shows and the wire conventions.\n;;\n");
    out.push_str(";; JS values are externref, as JS produced them. Per position, embed also\n");
    out.push_str(";; accepts anyref, and (ref extern) / (ref any) where the type admits\n");
    out.push_str(";; neither Null nor Undefined.\n;;\n");
    out.push_str(";; Unused imports need not be deleted; embed prunes to what you use.\n");
    out.push_str("(module\n");
    let imports: Vec<Import> = ir.imports().collect();
    if imports.iter().any(|i| i.member.variadic) {
        out.push_str("  (type $anyrefs (array (mut anyref)))\n");
    }

    out.push('\n');
    for sys in Sys::ALL {
        let params = sys
            .param()
            .map(|t| format!(" (param $x {})", t.wat()))
            .unwrap_or_default();
        let _ = writeln!(out, "  ;; {}", sys.js());
        let _ = writeln!(
            out,
            "  (import {} {} (func ${}{params}{}))",
            string(BINDINGS_SPECIFIER),
            string(sys.name()),
            ident(sys.name()),
            result(Some(sys.result()))
        );
    }

    if !ir.kinds.is_empty() {
        out.push_str("\n  ;; Kind discriminators: the index of the arm holding $x, -1 for none.\n");
    }
    for k in &ir.kinds {
        let id = match &k.module {
            Some(spec) => ident(&format!("{spec}:{}", k.discriminator())),
            None => ident(&k.discriminator()),
        };
        let _ = writeln!(
            out,
            "  (import {} {} (func ${id} (param $x externref) (result i32)))",
            string(k.specifier()),
            string(&k.discriminator()),
        );
    }

    let mut group = None;
    for import in &imports {
        let this_group = (import.module, import.class.map(|c| &c.name));
        if group != Some(this_group) {
            group = Some(this_group);
            out.push('\n');
        }
        let m = import.member;
        let id = match import.module {
            Some(spec) => ident(&format!("{spec}:{}", import.name())),
            None => ident(import.name()),
        };
        let receiver = if m.kind.has_receiver() {
            " (param $this externref)"
        } else {
            ""
        };
        let _ = writeln!(out, "  ;; {}", printer.member(import));
        let _ = writeln!(
            out,
            "  (import {} {} (func ${id}{receiver}{}{}))",
            string(import.specifier()),
            string(import.name()),
            wat_params(&m.params, m.variadic),
            result(m.result.wasm())
        );
    }

    out.push_str("\n  ;; `undefined`, for passing where a type admits Undefined.\n");
    let _ = writeln!(
        out,
        "  (import {} {} (global $undefined externref))",
        string(BUILTINS_SPECIFIER),
        string(UNDEFINED_GLOBAL)
    );
    out.push_str("  ;; JSPI: suspends on a Promise and returns its value. Importing this\n");
    out.push_str("  ;; selects JSPI mode in `embed`, which wraps the provides with promising.\n");
    let _ = writeln!(
        out,
        "  (import {} \"await\" (func $await (param externref) (result externref)))",
        string(BUILTINS_SPECIFIER)
    );

    if !ir.provides.is_empty() {
        out.push_str("\n  ;; --provides: fill these in; embed publishes them at their JS paths.\n");
    }
    for p in &ir.provides {
        // A promise provide always has a result: the promise itself, or
        // under JSPI the settled value.
        let ty = match (p.is_async, p.result.wasm()) {
            (true, None) => Some(WasmType::JS),
            (_, r) => r,
        };
        let _ = writeln!(out, "  ;; {}", printer.provide(p));
        let _ = writeln!(
            out,
            "  (func (export {}){}{} unreachable)",
            string(&p.name),
            wat_params(&p.params, false),
            result(ty)
        );
    }
    out.push_str(")\n");
    out
}

fn wat_params(params: &[Param], variadic: bool) -> String {
    params
        .iter()
        .enumerate()
        .map(|(i, p)| {
            let ty = if variadic && i + 1 == params.len() {
                ANYREFS
            } else {
                p.ty.wasm().unwrap_or(WasmType::JS).wat()
            };
            format!(" (param ${} {ty})", ident(&p.name))
        })
        .collect()
}
