//! The Rust side of `--provides`: a wrapper file of `#[wasm_bindgen]`
//! exported functions, one per [`ProvidedFn`], each delegating to the app
//! module at the same name, and an app scaffold to fill in.
//!
//! wasm-bindgen's `js_namespace` on exported functions spells the JS path:
//! `js_namespace = default` makes `export default { fetch }` and
//! `js_namespace = ["api", "math"]` the nested `api.math.add`. Parameters
//! arrive by value and results are owned, the export direction's types; a
//! `Promise<T>` result is an `async fn -> Result<T, JsValue>`.

use proc_macro2::TokenStream;
use quote::{format_ident, quote};

use super::typemap::{to_syn_type, CodegenContext, TypePosition};
use crate::ir::{ModuleContext, TypeRef};
use crate::provides::ProvidedFn;

/// Where the wrapper finds things.
pub struct ProvidesPaths {
    /// Module path of the generated bindings (`super::bindings`).
    pub bindings: syn::Path,
    /// Module path the wrapper delegates to (`super::app`).
    pub app: syn::Path,
}

/// The wrapper: `provides.rs`.
pub fn generate_wrapper(
    fns: &[ProvidedFn],
    cgctx: &CodegenContext<'_>,
    paths: &ProvidesPaths,
) -> anyhow::Result<String> {
    let bindings = &paths.bindings;
    let app = &paths.app;
    let items: Vec<TokenStream> = fns
        .iter()
        .map(|f| {
            let sig = signature(f, cgctx);
            let name = &sig.ident;
            let params = &sig.params;
            let args = &sig.args;
            let ret = &sig.ret;
            let attr = js_attr(f);
            let call = if sig.is_async {
                quote! { #app::#name(#(#args),*).await }
            } else {
                quote! { #app::#name(#(#args),*) }
            };
            let asyncness = sig.is_async.then(|| quote! { async });
            quote! {
                #attr
                pub #asyncness fn #name(#(#params),*) #ret {
                    #call
                }
            }
        })
        .collect();
    let tokens = quote! {
        #[allow(unused_imports)]
        use wasm_bindgen::prelude::*;
        #[allow(unused_imports)]
        use js_sys::*;
        #[allow(unused_imports)]
        use #bindings::*;
        #(#items)*
    };
    let header = "// Generated by ts-gen. Publishes the app's functions to JS at their paths.\n\n";
    Ok(format!(
        "{header}{}",
        spaced(&super::rustfmt_tokens(&tokens)?)
    ))
}

/// The app scaffold: the typed functions the wrapper delegates to, with
/// the TS JSDoc, bodies left for the author.
pub fn generate_app(
    fns: &[ProvidedFn],
    cgctx: &CodegenContext<'_>,
    paths: &ProvidesPaths,
) -> anyhow::Result<String> {
    let bindings = &paths.bindings;
    let items: Vec<TokenStream> = fns
        .iter()
        .map(|f| {
            let sig = signature(f, cgctx);
            let name = &sig.ident;
            let ret = &sig.ret;
            let doc = super::doc_tokens(&f.doc);
            let asyncness = sig.is_async.then(|| quote! { async });
            // Parameters are unused until the author fills the body in.
            let params: Vec<TokenStream> = sig
                .args
                .iter()
                .zip(&sig.param_types)
                .map(|(name, ty)| {
                    let name = format_ident!("_{name}");
                    quote! { #name: #ty }
                })
                .collect();
            let body = if sig.is_async {
                quote! { Err(JsValue::from_str("not implemented")) }
            } else if sig.unit {
                quote! {}
            } else {
                quote! { todo!() }
            };
            quote! {
                #doc
                pub #asyncness fn #name(#(#params),*) #ret {
                    #body
                }
            }
        })
        .collect();
    let tokens = quote! {
        #[allow(unused_imports)]
        use wasm_bindgen::prelude::*;
        #[allow(unused_imports)]
        use js_sys::*;
        #[allow(unused_imports)]
        use #bindings::*;
        #(#items)*
    };
    let header =
        "// Scaffold from ts-gen: the app behind the provides wrapper. Edit freely; it is not regenerated.\n\n";
    Ok(format!(
        "{header}{}",
        spaced(&super::rustfmt_tokens(&tokens)?)
    ))
}

/// A blank line between top-level items.
fn spaced(code: &str) -> String {
    let mut out = String::new();
    for line in code.lines() {
        if (line.starts_with("pub ") || line.starts_with("#[") || line.starts_with("///"))
            && out.ends_with("}\n")
        {
            out.push('\n');
        }
        out.push_str(line);
        out.push('\n');
    }
    out
}

struct Signature {
    ident: syn::Ident,
    params: Vec<TokenStream>,
    param_types: Vec<TokenStream>,
    args: Vec<syn::Ident>,
    ret: TokenStream,
    is_async: bool,
    unit: bool,
}

fn signature(f: &ProvidedFn, cgctx: &CodegenContext<'_>) -> Signature {
    let global = ModuleContext::Global;
    let ident = format_ident!("{}", super::signatures::public_rust_name(&f.rust_name));
    let args: Vec<syn::Ident> = f
        .params
        .iter()
        .map(|p| {
            format_ident!(
                "{}",
                super::signatures::public_rust_name(&crate::util::naming::to_snake_case(&p.name))
            )
        })
        .collect();
    // By value: the export direction owns its arguments, which is the
    // owned spelling return position already produces, and a parameter is
    // a read, so `T | null` arrives as `Option<T>`. An optional parameter
    // arrives as `Option<T>`, `None` when omitted.
    let param_types: Vec<TokenStream> = f
        .params
        .iter()
        .map(|p| {
            let ty = to_syn_type(
                &p.type_ref,
                TypePosition::RETURN,
                Some(cgctx),
                f.scope,
                &global,
            );
            if p.optional && p.type_ref.split_empties().is_none() {
                quote! { Option<#ty> }
            } else {
                ty
            }
        })
        .collect();
    let params: Vec<TokenStream> = args
        .iter()
        .zip(&param_types)
        .map(|(name, ty)| quote! { #name: #ty })
        .collect();
    let (is_async, result_ty) = match f.promise_inner() {
        Some(inner) => (true, inner),
        None => (false, &f.return_type),
    };
    let unit = matches!(result_ty, TypeRef::Void | TypeRef::Undefined);
    // The result is what JS receives, a write: `IntoWasmAbi` must pick what
    // an empty crosses as, so `T | null` is `Nullable<T>`, as an argument
    // of the bindings is.
    let ret = if is_async {
        if unit {
            quote! { -> Result<(), JsValue> }
        } else {
            let ty = to_syn_type(
                result_ty,
                TypePosition::EXPORT_RETURN,
                Some(cgctx),
                f.scope,
                &global,
            );
            quote! { -> Result<#ty, JsValue> }
        }
    } else if unit {
        quote! {}
    } else {
        let ty = to_syn_type(
            result_ty,
            TypePosition::EXPORT_RETURN,
            Some(cgctx),
            f.scope,
            &global,
        );
        quote! { -> #ty }
    };
    Signature {
        ident,
        params,
        param_types,
        args,
        ret,
        is_async,
        unit,
    }
}

fn js_attr(f: &ProvidedFn) -> TokenStream {
    let js_name = f.leaf();
    let namespace = &f.path[..f.path.len().saturating_sub(1)];
    match namespace {
        [] => quote! { #[wasm_bindgen(js_name = #js_name)] },
        [single] => {
            let ns = format_ident!("{single}");
            quote! { #[wasm_bindgen(js_namespace = #ns, js_name = #js_name)] }
        }
        many => quote! { #[wasm_bindgen(js_namespace = [#(#many),*], js_name = #js_name)] },
    }
}
