package tsgen.kotlin

/**
 * Writes Kotlin/Wasm bindings for an ABI template.
 *
 * * Flat layer: one `@JsFun` external per ABI function, in the package
 *   that makes its fully qualified name the ABI import name, so Kotlin
 *   imports it as `"js_code" "<name>"` and `ts-gen embed
 *   --bindings-module js_code` links it to the bindings.
 * * Typed layer, in [pkg]: an interface per owner over the JS value,
 *   members forwarding to the flat layer.
 * * Entry, in `[pkg].provided`: a `@JsExport` per handler, calling the
 *   user's function of the same name in [appPkg].
 */
class Gen(private val abi: Abi, private val pkg: String, private val appPkg: String) {
    private val bindings = "./bindings.wasm"
    private val owners: Map<String, Owner> = abi.owners.filter { it.module == null }.associateBy { it.path }
    private val skipped = mutableListOf<String>()
    private val flatAlias = mutableMapOf<String, String>() // ABI name -> import alias in the typed file
    private val supported: List<Func>

    init {
        supported = abi.functions.filter { f ->
            val why = when {
                f.module != bindings -> "module-scoped (\"${f.module}\")"
                f.alias != null -> "alias of ${f.alias}"
                f.variadic -> "variadic"
                !f.name.split('.').all(::isPlainIdent) -> "name is not a Kotlin identifier"
                else -> null
            }
            if (why != null) skipped += "\"${f.module}\" \"${f.name}\": $why"
            why == null
        }
        val used = mutableSetOf<String>()
        for (f in supported) {
            var a = "abi_" + sanitize(f.name.replace(".", "_")).replace("$", "_")
            while (!used.add(a)) a += "_"
            flatAlias[f.name] = a
        }
    }

    private fun T(path: String) = "$pkg.$path"

    private fun flatParam(s: Slot) = when (s.valtype) {
        // A Kotlin `Boolean` parameter of an external is passed as a JS
        // boolean (`externref`), so the ABI's i32 must be an `Int`.
        "i32" -> "kotlin.Int"
        "i64" -> "kotlin.Long"
        "f64" -> "kotlin.Double"
        else -> if (s.ref.empty) "kotlin.js.JsAny?" else "kotlin.js.JsAny"
    }

    private fun flatResult(s: Slot?) = when (s?.valtype) {
        null -> "kotlin.Unit"
        "i32" -> "kotlin.Boolean"
        else -> flatParam(s)
    }

    /** Relative path -> source, one file per package. */
    fun flatFiles(): Map<String, String> {
        val byPkg = supported.groupBy { it.name.substringBeforeLast('.', "") }
        return byPkg.entries.associate { (p, fs) ->
            val sb = StringBuilder()
            sb.append("// Generated by the ts-gen Kotlin generator from the ABI template. Do not edit.\n")
            sb.append("// Each external's fully qualified name is its ABI import name, so it is\n")
            sb.append("// imported as \"js_code\" \"<name>\" and linked by `ts-gen embed --bindings-module js_code`.\n")
            sb.append("@file:OptIn(kotlin.js.ExperimentalWasmJsInterop::class)\n")
            sb.append("@file:Suppress(\"unused\", \"FunctionName\", \"PackageName\", \"PackageDirectoryMismatch\", \"ObjectPropertyName\")\n")
            if (p.isNotEmpty()) sb.append("package ${p.split('.').joinToString(".") { q(it) }}\n")
            sb.append('\n')
            for (f in fs) {
                val member = f.name.substringAfterLast('.')
                f.ts?.let { sb.append("// ${it.replace("\n", " ")}\n") }
                val params = f.params.mapIndexed { i, s -> "${q(sanitize(s.name ?: "p$i"))}: ${flatParam(s)}" }
                val msg = f.name.replace("$", "\${'$'}")
                sb.append("@JsFun(\"() => { throw new Error('$msg: not linked by ts-gen embed') }\")\n")
                sb.append("external fun ${q(member)}(${params.joinToString(", ")}): ${flatResult(f.result)}\n\n")
            }
            "flat/${p.ifEmpty { "_root" }}.kt" to sb.toString()
        }
    }

    /** A position as the typed layer presents it. */
    private inner class TType(
        val type: String,
        /** Kotlin value -> flat argument. */
        val toFlat: (String) -> String,
        /** Flat value -> Kotlin value. */
        val fromFlat: (String) -> String,
    ) {
        /** The type for overload clashes: Kotlin rejects overloads differing only in nullability. */
        val erased get() = type.removeSuffix("?")
    }

    private fun ttype(s: Slot): TType {
        val id = { x: String -> x }
        return when (s.valtype) {
            "i32" -> TType("kotlin.Boolean", { "(if ($it) 1 else 0)" }, id)
            "i64" -> TType("kotlin.Long", id, id)
            "f64" -> TType("kotlin.Double", id, id)
            else -> refType(s.ref)
        }
    }

    private fun refType(r: Ref): TType {
        val n = if (r.empty) "?" else ""
        val dot = if (r.empty) "?." else "."
        // Kotlin cannot produce `undefined` (FINDINGS.md), so an empty
        // argument is always passed as `null`, even where TS admits only
        // `undefined`.
        return when (val h = r.head) {
            is Head.OwnerRef -> when {
                // Module owners are not bound; a namespace is not a value type.
                h.module == null && owners[h.path]?.let { it.kind != "namespace" } == true -> TType(T(h.path) + n, { "$it${dot}ref" }, {
                    if (r.empty) "$it?.let { ${T(h.path)}.wrap(it) }" else "${T(h.path)}.wrap($it)"
                })
                // Not an owner of this ABI, but a JS builtin Kotlin has a type for.
                h.module == null && h.path == "Promise" -> TType("kotlin.js.Promise<kotlin.js.JsAny?>$n", { it },
                    { "$it${dot}unsafeCast<kotlin.js.Promise<kotlin.js.JsAny?>>()" })
                else -> TType("kotlin.js.JsAny$n", { it }, { it })
            }
            Head.Str -> TType("kotlin.String$n", { "$it${dot}toJsString()" },
                { "$it${dot}unsafeCast<kotlin.js.JsString>()${dot}toString()" })
            Head.Num -> TType("kotlin.Double$n", { "$it${dot}toJsNumber()" },
                { "$it${dot}unsafeCast<kotlin.js.JsNumber>()${dot}toDouble()" })
            Head.Bool -> TType("kotlin.Boolean$n", { "$it${dot}toJsBoolean()" },
                { "$it${dot}unsafeCast<kotlin.js.JsBoolean>()${dot}toBoolean()" })
            // No Kotlin/Wasm stdlib conversion between Long and a JS bigint.
            Head.BigInt, null -> TType("kotlin.js.JsAny$n", { it }, { it })
        }
    }

    private enum class Kind { PROP, FUN, CTOR, SETTER }

    private inner class Member(
        val func: Func,
        val container: String?, // owner path, null at top level
        val static: Boolean,
        val kind: Kind,
        val family: String,
        val jsName: String,
        val params: List<Pair<String, TType>>, // without the receiver
        val result: TType?,
    ) {
        var name: String = ""
        var override = false
        val types get() = params.map { it.second.type } + (result?.type ?: "")
        val sig get() = params.joinToString(",") { it.second.erased }
        /** Kotlin's clash key: properties by name, functions by name and parameter types. */
        val key get() = if (kind == Kind.PROP) "val $name" else "fun $name($sig)"

        fun render(indent: String, override: Boolean = this.override): String {
            val sb = StringBuilder(kdoc(indent, func.doc, func.ts))
            val args = mutableListOf<String>()
            if (!static && container != null && func.op is Op.Member) args += "ref"
            params.forEach { (n, t) -> args += t.toFlat(q(n)) }
            val call = "${flatAlias.getValue(func.name)}(${args.joinToString(", ")})"
            val body = result?.fromFlat?.invoke(call) ?: call
            val ret = result?.type ?: "kotlin.Unit"
            val ps = params.joinToString(", ") { (n, t) -> "${q(n)}: ${t.type}" }
            val ov = if (override) "override " else ""
            when (kind) {
                Kind.PROP -> sb.append("$indent${ov}val ${q(name)}: $ret\n$indent    get() = $body\n")
                Kind.CTOR -> sb.append("$indent${if (name == "invoke") "operator " else ""}fun ${q(name)}($ps): $ret = $body\n")
                else -> sb.append("$indent${ov}fun ${q(name)}($ps): $ret = $body\n")
            }
            return sb.toString()
        }
    }

    private fun memberPart(f: Func) =
        if (f.owner != null && f.name.startsWith(f.owner + ".")) f.name.removePrefix(f.owner + ".") else f.name.substringAfterLast('.')

    private fun buildMember(f: Func): Member? {
        val op = f.op ?: return null
        val ps = f.params.mapIndexed { i, s -> s to i }
        fun typed(from: Int) = ps.drop(from).map { (s, i) ->
            var n = sanitize(s.name ?: "p$i")
            if (n == "ref") n = "ref_" // would shadow the receiver's `ref`
            n to ttype(s)
        }
        val res = f.result?.let(::ttype)
        return when (op) {
            is Op.Member -> {
                val instance = op.on == null
                if (instance && (f.owner == null || f.owner !in owners)) return null
                val container = if (instance) f.owner else f.owner?.takeIf { it in owners }
                val params = typed(if (instance) 1 else 0)
                val kind = when (op.kind) {
                    "get" -> if (params.isEmpty()) Kind.PROP else Kind.FUN
                    "set" -> Kind.SETTER
                    else -> Kind.FUN
                }
                Member(f, container, !instance, kind, "${op.kind} ${op.name} ${op.on}", op.name, params, res)
            }
            is Op.New -> if (f.owner in owners) Member(f, f.owner, true, Kind.CTOR, "new", "new", typed(0), res) else null
            Op.Object -> if (f.owner in owners) Member(f, f.owner, true, Kind.CTOR, "new", "new", typed(0), res) else null
            else -> null // sys functions: flat layer only
        }
    }

    private fun baseName(m: Member) = when (m.kind) {
        Kind.PROP -> sanitize(m.jsName)
        Kind.SETTER -> "set" + sanitize(m.jsName).replaceFirstChar(Char::uppercase)
        Kind.CTOR -> "invoke"
        Kind.FUN -> sanitize(m.jsName)
    }

    private val reservedInstance = setOf("val ref", "fun toString()", "fun hashCode()", "fun equals(kotlin.js.JsAny?)")

    /**
     * Names one container's members: an overload family shares its JS
     * name where the Kotlin signatures differ; a clash takes the ABI
     * name's member part, camel-cased (`jsonWithInit`).
     */
    private fun nameMembers(ms: List<Member>, taken: MutableSet<String>, inherited: Map<String, Member> = emptyMap()) {
        for (m in ms) {
            m.name = baseName(m)
            val base = inherited[m.key]
            if (base != null) {
                // Redeclared from a base: an override where Kotlin allows one.
                if (m.kind != Kind.CTOR && base.types == m.types) { m.override = true; taken += m.key; continue }
                m.name = camel(memberPart(m.func))
            }
            if (m.key in taken) m.name = camel(memberPart(m.func))
            while (m.key in taken || m.key in inherited) m.name += "_"
            taken += m.key
        }
    }

    private class Node(val name: String, val path: String) {
        var owner: Owner? = null
        val children = linkedMapOf<String, Node>()
    }

    fun typedFile(): String {
        val members = supported.mapNotNull(::buildMember)
        val byContainer = members.groupBy { it.container }

        // Instance members by owner, bases first, so derived owners see their bases' names.
        val views = mutableMapOf<String, View>()
        fun viewOf(path: String): View = views.getOrPut(path) {
            val v = View()
            views[path] = v // a cycle sees an empty view
            for (b in owners[path]?.extends.orEmpty().filter { it.module == null && it.path in owners }.map { it.path }) {
                val bv = viewOf(b)
                // Kotlin needs one type per member: a base that disagrees
                // with an earlier one is not a supertype, and its other
                // members are declared here instead.
                val conflict = bv.all.any { (k, m) -> v.all[k]?.let { it !== m && it.types != m.types } == true }
                if (conflict) {
                    for ((k, m) in bv.all) if (k !in v.all) { v.all[k] = m; v.copied += m }
                    continue
                }
                v.bases += b
                for ((k, m) in bv.all) {
                    val prev = v.all[k]
                    if (prev == null) { v.all[k] = m; v.via[k] = b }
                    else if (prev !== m) {
                        // Two declarations with the same types: Kotlin wants an explicit override.
                        val pv = v.via[k]
                        if (pv != null) v.diamonds += m to pv else v.copiedOverride += prev
                    }
                }
            }
            val ms = byContainer[path].orEmpty().filter { !it.static }
            // A redeclaration here wins over a copied member, as in TS.
            val copiedKeys = v.copied.map { it.key }.toSet()
            nameMembers(ms, reservedInstance.toMutableSet(), v.all.filterKeys { it !in copiedKeys })
            v.own += ms
            ms.forEach { v.all[it.key] = it }
            v.copied.removeAll { c -> ms.any { it.key == c.key } }
            v.diamonds.removeAll { (m, _) -> ms.any { it.key == m.key } || v.copied.any { it.key == m.key } }
            v
        }
        owners.keys.forEach { viewOf(it) }
        for ((c, ms) in byContainer) if (c != null) nameMembers(ms.filter { it.static }, mutableSetOf("fun wrap(kotlin.js.JsAny)"))
        // A global `const Cloudflare: Cloudflare` would clash with the
        // interface (its companion makes the name a value too).
        nameMembers(byContainer[null].orEmpty(), owners.keys.map { "val " + it.substringBefore('.') }.toMutableSet())

        // The owner tree: `WebAssembly.Module` nests in `WebAssembly`.
        val root = Node("", "")
        for (o in owners.values) {
            var n = root
            for (seg in o.path.split('.')) {
                val p = if (n.path.isEmpty()) seg else "${n.path}.$seg"
                n = n.children.getOrPut(seg) { Node(seg, p) }
            }
            n.owner = o
        }

        val sb = StringBuilder()
        sb.append("// Generated by the ts-gen Kotlin generator from the ABI template. Do not edit.\n")
        sb.append("@file:OptIn(kotlin.js.ExperimentalWasmJsInterop::class)\n")
        sb.append("@file:Suppress(\"unused\", \"FunctionName\", \"PropertyName\", \"ObjectPropertyName\", \"ClassName\", \"RedundantSuppression\")\n")
        sb.append("package $pkg\n\n")
        for (f in supported) {
            val p = f.name.split('.').joinToString(".") { q(it) }
            sb.append("import $p as ${flatAlias.getValue(f.name)}\n")
        }
        if (skipped.isNotEmpty()) {
            sb.append("\n// Not bound by this prototype (module-scoped imports, alias imports and\n// variadic functions are out of scope):\n")
            skipped.forEach { sb.append("//   $it\n") }
        }
        sb.append("\n/** A JS value the bindings wrap. */\ninterface JsHandle {\n    val ref: kotlin.js.JsAny\n}\n\n")

        fun emitNode(n: Node, indent: String) {
            val o = n.owner
            val statics = byContainer[n.path].orEmpty().filter { it.static }
            val name = q(n.name)
            if (o == null || o.kind == "namespace") {
                sb.append(kdoc(indent, o?.doc, null))
                sb.append("${indent}object $name {\n")
                statics.forEach { sb.append(it.render("$indent    ")) }
                n.children.values.forEach { emitNode(it, "$indent    ") }
                sb.append("$indent}\n")
                return
            }
            val v = views.getValue(n.path)
            val bases = v.bases.map(::T).ifEmpty { listOf("$pkg.JsHandle") }
            sb.append(kdoc(indent, o.doc, null))
            sb.append("${indent}interface $name : ${bases.joinToString(", ")} {\n")
            v.own.forEach { sb.append(it.render("$indent    ")) }
            v.copied.forEach { sb.append(it.render("$indent    ", override = it in v.copiedOverride)) }
            v.diamonds.forEach { (m, via) ->
                val ps = m.params.joinToString(", ") { (pn, t) -> "${q(pn)}: ${t.type}" }
                val args = m.params.joinToString(", ") { q(it.first) }
                val ret = m.result?.type ?: "kotlin.Unit"
                if (m.kind == Kind.PROP) sb.append("$indent    override val ${q(m.name)}: $ret get() = super<${T(via)}>.${q(m.name)}\n")
                else sb.append("$indent    override fun ${q(m.name)}($ps): $ret = super<${T(via)}>.${q(m.name)}($args)\n")
            }
            sb.append("$indent    companion object {\n")
            sb.append("$indent        fun wrap(ref: kotlin.js.JsAny): ${T(n.path)} = Impl(ref)\n")
            sb.append("$indent        private class Impl(override val ref: kotlin.js.JsAny) : ${T(n.path)}\n")
            statics.forEach { sb.append(it.render("$indent        ")) }
            sb.append("$indent    }\n")
            n.children.values.forEach { emitNode(it, "$indent    ") }
            sb.append("$indent}\n")
        }
        for (n in root.children.values) { emitNode(n, ""); sb.append('\n') }

        for (o in owners.values) for (a in o.aliases) if (isPlainIdent(a) && '.' !in a) sb.append("typealias ${q(a)} = ${T(o.path)}\n")

        byContainer[null].orEmpty().forEach { sb.append(it.render("")).append('\n') }
        return sb.toString()
    }

    /** An owner's instance members as its Kotlin interface sees them. */
    private inner class View {
        val bases = mutableListOf<String>() // Kotlin supertypes
        val all = linkedMapOf<String, Member>() // by clash key, own included
        val via = mutableMapOf<String, String>() // key -> the supertype providing it
        val own = mutableListOf<Member>()
        val copied = mutableListOf<Member>() // from bases that are not supertypes
        val copiedOverride = mutableSetOf<Member>()
        val diamonds = mutableListOf<Pair<Member, String>>() // override delegating to a supertype
    }

    fun entryFile(): String? {
        if (abi.handlers.isEmpty()) return null
        val sb = StringBuilder()
        sb.append("// Generated by the ts-gen Kotlin generator from the ABI template. Do not edit.\n")
        sb.append("// One export per handler: wraps the wire values and calls `$appPkg.<name>`.\n")
        sb.append("@file:OptIn(kotlin.js.ExperimentalWasmJsInterop::class, kotlinx.coroutines.DelicateCoroutinesApi::class)\n")
        sb.append("package $pkg.provided\n\n")
        sb.append("import kotlinx.coroutines.CoroutineStart\nimport kotlinx.coroutines.GlobalScope\nimport kotlinx.coroutines.promise\n\n")
        for (h in abi.handlers) {
            val ps = h.params.mapIndexed { i, s -> sanitize(s.name ?: "p$i") to s }
            val wire = ps.joinToString(", ") { (n, s) ->
                // A `Boolean` export parameter is an i32, as the ABI wants.
                "${q(n)}: ${if (s.valtype == "i32") "kotlin.Boolean" else flatParam(s)}"
            }
            val args = ps.joinToString(", ") { (n, s) -> ttype(s).fromFlat(q(n)) }
            val call = "$appPkg.${appName(h)}($args)"
            val res = h.result?.let(::ttype)
            fun back(v: String) = when (h.result?.valtype) {
                null -> v
                "i32" -> "(if ($v) 1 else 0)" // a `Boolean` export result would be a JS boolean
                else -> res!!.toFlat(v)
            }
            val wireRes = when (h.result?.valtype) {
                null -> "kotlin.Unit"
                "i32" -> "kotlin.Int"
                else -> flatParam(h.result)
            }
            sb.append(kdoc("", h.doc, h.ts))
            // The export name may be dotted (`api.math.add`); @JsName sets it.
            sb.append("@JsExport\n@JsName(\"${h.export.replace("$", "\${'$'}")}\")\n")
            if (h.promise) {
                // Not JSPI: the export returns the promise, which `promise {}` makes.
                val v = if (h.result == null) "$call.let { null }" else back(call)
                sb.append("fun ${appName(h)}($wire): kotlin.js.JsAny =\n")
                sb.append("    GlobalScope.promise(start = CoroutineStart.UNDISPATCHED) { $v }\n\n")
            } else {
                sb.append("fun ${appName(h)}($wire): $wireRes = ${back(call)}\n\n")
            }
        }
        return sb.toString()
    }

    /** The user functions the entry calls, for a scaffold. */
    fun appSignatures(): String = abi.handlers.joinToString("\n") { h ->
        val ps = h.params.mapIndexed { i, s -> "${q(sanitize(s.name ?: "p$i"))}: ${ttype(s).type}" }
        val res = h.result?.let { ttype(it).type } ?: "Unit"
        (if (h.promise) "suspend " else "") + "fun ${appName(h)}(${ps.joinToString(", ")}): $res"
    }

    /** The user function a handler calls: its export name, `.` as `_` (`api_math_add`). */
    private fun appName(h: Handler) = q(sanitize(h.export.replace('.', '_')))
}
